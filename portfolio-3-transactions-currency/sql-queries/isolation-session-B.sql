
USE SecureBankDB;
GO

SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;
SELECT 'B: READ UNCOMMITTED (dirty read)' AS Step, Balance, SYSDATETIME() AS ReadAt
FROM dbo.Accounts WHERE AccountNumber = '1000000001';

SET TRANSACTION ISOLATION LEVEL READ COMMITTED;
SELECT 'B: READ COMMITTED (waited for A)' AS Step, Balance, SYSDATETIME() AS ReadAt
FROM dbo.Accounts WHERE AccountNumber = '1000000001';
GO
